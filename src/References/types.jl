# The references of a problem as values (#409): an analytic solution of the continuous
# problem, or a solve of the discretized problem with how it was obtained. Built from the
# metadata and from the generated reference files, never written by hand.

"""
$(TYPEDEF)

A reference solution of a problem: its objective, read with `objective(ref)`.

Two kinds, with different data: [`AnalyticReference`](@ref), the solution of the continuous
problem, and [`NumericalReference`](@ref), a solve of the discretized problem.
"""
abstract type AbstractReference end

"""
$(TYPEDSIGNATURES)

The objective of the reference `ref`. Every subtype of `AbstractReference` implements it.
"""
function CTModels.Components.objective(ref::AbstractReference)
    return throw(
        CTBase.Exceptions.NotImplemented(
            "objective is not implemented for $(typeof(ref))";
            required_method="objective(::$(typeof(ref)))",
            suggestion="define it for every subtype of AbstractReference",
        ),
    )
end

"""
$(TYPEDEF)

The analytic solution of the continuous problem `problem` for `parameters` (#379): `state`
and `control`, functions of the time, the `objective`, and the `source` it comes from. The
objective of a discretized problem differs from it by the discretization error.

# Fields

$(TYPEDFIELDS)
"""
struct AnalyticReference{S,U} <: AbstractReference
    "Name of the problem."
    problem::Symbol
    "Parameters of the problem the solution is for."
    parameters::Union{Nothing,NamedTuple}
    "Objective of the continuous problem."
    objective::Float64
    "State, a function of the time."
    state::S
    "Control, a function of the time."
    control::U
    "Where the solution comes from (a publication)."
    source::String
end

CTModels.Components.objective(ref::AnalyticReference) = ref.objective

"""
$(TYPEDEF)

A known solution of the problem `problem` discretized on `grid_size` steps with `scheme`
(#378), and how it was obtained (#409): one of the solves that reached it, chosen to
represent it (a strict convergence before an acceptable one, then the smallest constraint
violation), with its modeling, modeler, solver and every option of the solver, its exit
status, iterations, time and constraint violation, and the environment of its run.

Generated by `tools/references/update.jl` from the convergence and robustness tests. The
trajectories are not kept: the configuration is enough to solve again.

# Fields

$(TYPEDFIELDS)
"""
struct NumericalReference <: AbstractReference
    "Name of the problem."
    problem::Symbol
    "Discretization scheme, e.g. `:trapeze`."
    scheme::Symbol
    "Number of steps of the grid."
    grid_size::Int
    "Objective of the solve."
    objective::Float64
    "Number of solves, every modeling, configuration and platform, that reached the solution."
    solves::Int
    "The configurations that reached it, `\"<modeling> <configuration>\"`."
    configurations::Vector{String}
    "Modeling of the solve, e.g. `:OptimalControl`."
    modeling::Symbol
    "Configuration of the solve, as the tests name it."
    configuration::String
    "Modeler of the solve (`:adnlp`, `:exa`), `nothing` for JuMP."
    modeler::Union{Nothing,Symbol}
    "Solver of the solve, e.g. `:ipopt`."
    solver::Symbol
    "Every option given to the solver, defaults included."
    options::NamedTuple
    "Exit status of the solver, e.g. `:first_order`, `:LOCALLY_SOLVED`, `:acceptable`."
    status::Symbol
    "Number of iterations."
    iterations::Int
    "Solve time in seconds, on `platform`."
    time::Float64
    "Largest violation of the constraints, as the modeling measures it."
    violation::Float64
    "Platform of the run, e.g. `cron-OptimalControl-1.13-ubuntu-latest`."
    platform::String
    "The run that solved it (a GitHub Actions run), or `local`."
    run::String
    "Commit of the package."
    commit::String
    "Julia version."
    julia::VersionNumber
    "Operating system, architecture and processor of the platform."
    machine::NamedTuple{(:os, :arch, :cpu),Tuple{String,String,String}}
    "Versions of the packages that modeled, discretized and solved it."
    versions::NamedTuple
end

CTModels.Components.objective(ref::NumericalReference) = ref.objective

# A TOML table as a `NamedTuple` with sorted keys, so that two equal tables give equal values.
_namedtuple(table) = (; (Symbol(k) => table[k] for k in sort!(collect(keys(table))))...)

# The `NumericalReference` of a known solution, from its table in a reference file, or
# `nothing` for a file written before #409. Such a file still loads, so that
# `tools/references/update.jl`, which loads the package, can write it again; the consistency
# tests fail on it.
function _numerical_reference(problem::Symbol, scheme::Symbol, grid_size::Int, solution)
    haskey(solution, "reference") || return nothing
    r = solution["reference"]
    return NumericalReference(
        problem,
        scheme,
        grid_size,
        Float64(solution["objective"]),
        Int(solution["solves"]),
        String.(solution["configurations"]),
        Symbol(r["modeling"]),
        r["configuration"],
        isempty(r["modeler"]) ? nothing : Symbol(r["modeler"]),
        Symbol(r["solver"]),
        _namedtuple(r["options"]),
        Symbol(r["status"]),
        Int(r["iterations"]),
        Float64(r["time"]),
        Float64(r["violation"]),
        r["platform"],
        r["run"],
        r["commit"],
        VersionNumber(r["julia"]),
        (os=r["os"], arch=r["arch"], cpu=r["cpu"]),
        _namedtuple(r["versions"]),
    )
end

function Base.show(io::IO, ref::NumericalReference)
    return print(io, "NumericalReference(:", ref.problem, ", ", ref.objective, ")")
end

function Base.show(io::IO, ::MIME"text/plain", ref::NumericalReference)
    println(
        io,
        "Known solution of ",
        ref.problem,
        ", ",
        ref.scheme,
        " on ",
        ref.grid_size,
        " steps",
    )
    println(io, "  objective:  ", ref.objective, " (", ref.solves, " solves)")
    modeler = isnothing(ref.modeler) ? "" : string(ref.modeler, " + ")
    println(io, "  solved by:  ", ref.modeling, ", ", modeler, ref.solver, ", ", ref.status)
    println(io, "  iterations: ", ref.iterations, ", violation ", ref.violation)
    return print(io, "  run:        ", ref.run, " (", ref.platform, ")")
end

function Base.show(io::IO, ref::AnalyticReference)
    return print(io, "AnalyticReference(:", ref.problem, ", ", ref.objective, ")")
end
