# Metadata schema: the required and optional fields of `ext/MetaData/<problem>.jl`, with
# their types, and the fields generated by tools, never written in these files. Checked here
# at load time and by the consistency tests.
const METADATA_SCHEMA = (
    required=(
        grid_size=Int, parameters=Union{Nothing,NamedTuple}, status=NamedTuple, init=Function
    ),
    optional=(notes=AbstractString, reference_solution=Function),
    generated=(reference_objective=NamedTuple,),
)
const METADATA_STORAGE = OrderedDict{Symbol,OrderedDict}()

# Reference objectives (#375): one file per problem, `ext/MetaData/references/<problem>.toml`,
# written by `tools/references/update.jl` from the results of the convergence tests, one
# table per scheme. Read into the field `:reference_objective` of the metadata.
const REFERENCES_PATH = joinpath(METADATA_PATH, "references")
# The fields of a table, and how each is read: a type, or a function of the TOML value.
const REFERENCE_FIELDS = (
    value=Float64,
    grid_size=Int,
    parameters=String,
    source=Symbol,
    agreement=Bool,
    spread=Float64,
    run=String,
    # the known solutions (#378): the objectives of the distinct solutions reached, best first
    solutions=tables -> Float64[t["objective"] for t in tables],
)

"""
Relative gap below which two objectives are the same solution (#378): above the accuracy of
the solvers at the tolerance of the tests (about 1e-6 at `tol = 1e-8`), below the gap between
the known local solutions (1.6e-4 on `mountain_car`). Used to group the solutions reached,
to say whether the configurations agree, and to say which solution a solve reached.
"""
const SAME_SOLUTION = 1e-5

"""Relative gap of `a` to `b` (absolute when `b` is zero)."""
_relative_gap(a, b) = abs(a - b) / (iszero(b) ? 1 : abs(b))
# a new directory changes `METADATA_PATH`, already a dependency
isdir(REFERENCES_PATH) && Base.include_dependency(REFERENCES_PATH)

function _references(problem::Symbol, file::AbstractString=joinpath(REFERENCES_PATH, "$(problem).toml"))
    isfile(file) || return nothing
    Base.include_dependency(file)
    entries = Pair{Symbol,NamedTuple}[]
    for (scheme, table) in TOML.parsefile(file)
        table isa AbstractDict || error("Reference objective $(scheme) of $(problem): not a table")
        values = map(keys(REFERENCE_FIELDS)) do key
            haskey(table, string(key)) ||
                error("Missing field $(key) in the reference objective $(scheme) of $(problem)")
            return REFERENCE_FIELDS[key](table[string(key)])
        end
        push!(entries, Symbol(scheme) => NamedTuple{keys(REFERENCE_FIELDS)}(values))
    end
    return NamedTuple(entries)
end

for problem in PROBLEM_NAMES
    raw = eval(Symbol(problem, :_meta))
    data = OrderedDict{Symbol,Any}()
    for (key, T) in pairs(METADATA_SCHEMA.required)
        haskey(raw, key) || error("Missing metadata $(key) for $(problem)")
        raw[key] isa T || error(
            "Type mismatch: Expected $(T) for $(key) of $(problem), but got $(typeof(raw[key]))",
        )
        data[key] = raw[key]
    end
    for (key, value) in raw
        haskey(METADATA_SCHEMA.required, key) && continue
        haskey(METADATA_SCHEMA.optional, key) ||
            error("Unknown metadata $(key) for $(problem)")
        T = METADATA_SCHEMA.optional[key]
        value isa T || error(
            "Type mismatch: Expected $(T) for $(key) of $(problem), but got $(typeof(value))",
        )
        data[key] = value
    end
    references = _references(problem)
    isnothing(references) || (data[:reference_objective] = references)
    METADATA_STORAGE[problem] = data
end

# Generic methods are installed before weak-dependency extensions load.
for problem in PROBLEM_NAMES
    doc = """Return the `$problem` problem for a selected modeling.

Available modelings and statuses are listed by `OptimalControlProblems.status(:$problem)`."""
    code = quote
        @doc $doc function $(problem)(
            model_backend::T, args...; kwargs...
        ) where {T<:AbstractModelBackend}
            spec = _modeling_spec(model_backend)
            if !_problem_exists($(QuoteNode(problem)), spec)
                throw(
                    CTBase.Exceptions.IncorrectArgument(
                        string(
                            $(QuoteNode(problem)),
                            " is not available for ",
                            spec.name,
                            "Backend; see problems(",
                            spec.name,
                            "Backend())",
                        ),
                    ),
                )
            end
            _warn_if_draft($(QuoteNode(problem)), spec.name)
            throw(CTBase.Exceptions.ExtensionError(WEAKDEPS[T]))
        end
    end
    eval(code)
    @eval export $problem
end

"""
$(TYPEDSIGNATURES)

Return the dictionary containing the metadata of all available optimal control problems.

# Example

```julia-repl
julia> problem_metadata()
```
"""
problem_metadata() = METADATA_STORAGE

"""
$(TYPEDSIGNATURES)

Return a dictionary containing the metadata of `problem`, without building it.

The metadata of a built problem is read with `metadata(pb)` on the [`Problem`](@ref).
The following keys are valid:

- `grid_size::Int`: the default number of steps. For example:
```julia
:grid_size => 500,
```
- `parameters::Union{Nothing,NamedTuple}`: the list of parameters. For example:
```julia
:parameters => (
    t0 = 0,
    tf = 1,
    x₁_l = 0,
    x₁_u = 0.1,
    x₁_t0 = 0,
    x₂_t0 = 1,
    x₁_tf = 0,
    x₂_tf = -1,
),
```
- `status`: the status (`:valid` or `:draft`) of the problem in each modeling.
- `init`: the initial guess of every modeling, a function of the parameters (see
  `OptimalControlProblems.initial_guess_data`).
- `reference_solution` (optional): the analytic solution of the continuous problem, a
  function of the parameters; see [`OptimalControlProblems.reference_solution_data`](@ref).

# Example

```julia-repl
julia> data = problem_metadata(:beam)
julia> data[:grid_size]
500
```
"""
function problem_metadata(problem::Symbol)
    haskey(METADATA_STORAGE, problem) || throw(
        CTBase.Exceptions.IncorrectArgument(
            "unknown problem";
            got="$(problem)",
            expected="one of the problems of the collection",
            suggestion="list them with problems(; status=:all)",
        ),
    )
    return METADATA_STORAGE[problem]
end

