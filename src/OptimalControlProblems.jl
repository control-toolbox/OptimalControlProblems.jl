# ------- Available Problems Function -------
"""
$(TYPEDSIGNATURES)

Returns the sorted list of optimal control problems.

Availability comes from the model files present in `ext/<modeling>Models/`; the status
(`:valid` or `:draft`) of each problem in each modeling comes from its metadata.

- `problems()`: problems having the requested `status` in **at least one** modeling.
- `problems(backend)`: problems available in that modeling with the requested `status`.
- `problems(backend1, backend2, ...)`: problems available in **all** the given modelings
  with the requested `status`, which is the list to use to compare modelings.

# Keyword arguments

- `status::Symbol=:valid`: `:valid`, `:draft` or `:all`.

# Returns

- `Vector{Symbol}`: A vector of problem names as symbols.

# Example

```julia-repl
julia> OptimalControlProblems.problems(JuMPBackend(), OptimalControlBackend())
[:balanced_field, :beam, ...]
```
"""
function problems(; status::Symbol=:valid)::Vector{Symbol}
    return _select_problems(MODELING_SPECS, status; require_all=false)
end

function problems(backend::AbstractModelBackend; status::Symbol=:valid)::Vector{Symbol}
    return _select_problems((_modeling_spec(backend),), status)
end

function problems(
    first::AbstractModelBackend, rest::AbstractModelBackend...; status::Symbol=:valid
)::Vector{Symbol}
    modelings = (_modeling_spec(first), (_modeling_spec(backend) for backend in rest)...)
    return _select_problems(modelings, status)
end

"""
$(TYPEDSIGNATURES)

Return the status of `problem` in each modeling where it exists.
"""
function status(problem::Symbol)
    haskey(METADATA_STORAGE, problem) || throw(
        CTBase.Exceptions.IncorrectArgument(
            "There is no problem named $problem in metadata"
        ),
    )
    return METADATA_STORAGE[problem][:status]
end

"""
$(TYPEDSIGNATURES)

Return the number of discretisation steps, from the metadata, for a given optimal control problem.

# Arguments

- `problem::Symbol`: The name of the problem.

# Returns

- `Int`: The number of discretisation steps (`N`) of the specified problem.

# Example

```julia-repl
julia> grid_size_data(:beam)
500
```
"""
function grid_size_data(problem::Symbol)
    return problem_metadata(problem)[:grid_size]
end

"""
$(TYPEDSIGNATURES)

Return the reference objective of `problem` discretized on `grid_size` steps with `scheme`,
or `nothing` when the problem has none for this discretization.

The reference objectives are computed from the convergence tests of every modeling and
configuration, by `tools/references/update.jl`: the best objective among the solves that
converged. They are stored in `problem_metadata(problem)[:reference_objective]`, with how
they were obtained.

# Example

```julia-repl
julia> OptimalControlProblems.reference_objective(:beam)
8.889...
```
"""
function reference_objective(
    problem::Symbol; grid_size::Int=grid_size_data(problem), scheme::Symbol=:trapeze
)
    references = get(problem_metadata(problem), :reference_objective, nothing)
    isnothing(references) && return nothing
    entry = get(references, scheme, nothing)
    (isnothing(entry) || entry.grid_size != grid_size) && return nothing
    return entry.value
end

"""
$(TYPEDSIGNATURES)

Return the analytic solution of the continuous `problem` for `parameters` (merged with the
default ones), or `nothing` when none is known for them: a named tuple with `state` and
`control`, functions of the time, the `objective`, and its `source`.

It is the solution of the continuous problem: the objective of a discretized problem differs
from it by the discretization error, which the reference objective includes.

# Example

```julia-repl
julia> OptimalControlProblems.reference_solution_data(:beam).objective
8.88888888888889
```
"""
function reference_solution_data(
    problem::Symbol, parameters::Union{Nothing,NamedTuple}=nothing
)
    solution = get(problem_metadata(problem), :reference_solution, nothing)
    isnothing(solution) && return nothing
    return solution(parameters_data(problem, parameters))
end

"""
$(TYPEDSIGNATURES)

Which known solution of `problem` the objective `objective` is, for the discretization on
`grid_size` steps with `scheme` (#378): `:best` (the reference objective), `:local` (another
known solution), `:new` (none of them), or `nothing` when the problem has no reference for
this discretization. Two objectives are the same solution within a relative
`OptimalControlProblems.SAME_SOLUTION`.
"""
function solution_kind(
    problem::Symbol,
    objective::Real;
    grid_size::Int=grid_size_data(problem),
    scheme::Symbol=:trapeze,
)
    reference = reference_objective(problem; grid_size, scheme)
    isnothing(reference) && return nothing
    _relative_gap(objective, reference) <= SAME_SOLUTION && return :best
    solutions = problem_metadata(problem)[:reference_objective][scheme].solutions
    any(s -> _relative_gap(objective, s) <= SAME_SOLUTION, solutions) && return :local
    return :new
end

"""
$(TYPEDSIGNATURES)

Merge two `Nothing` values.

# Arguments

- `::Nothing`: first argument.
- `::Nothing`: second argument.

# Returns

- `nothing::Nothing`: always returns `nothing`.

# Example

```julia-repl
julia> merge(nothing, nothing)
nothing
```
"""
merge(::Nothing, ::Nothing) = nothing

"""
$(TYPEDSIGNATURES)

Merge a `NamedTuple` with `nothing`.  

# Arguments

- `A::NamedTuple`: a named tuple to keep.
- `::Nothing`: placeholder, ignored.

# Returns

- `::NamedTuple`: returns `A` unchanged.

# Example

```julia-repl
julia> merge((a=1,), nothing)
(a = 1,)
```
"""
merge(A::NamedTuple, ::Nothing) = A

"""
$(TYPEDSIGNATURES)

Throw an error when attempting to merge `nothing` with a `NamedTuple`.  

# Arguments

- `::Nothing`: indicates there is no data to merge.
- `::NamedTuple`: the data that cannot be merged.

# Returns

- This function always throws `CTBase.Exceptions.PreconditionError`.

# Example

```julia-repl
julia> merge(nothing, (a=1,))
ERROR: PreconditionError: there is nothing to merge
```
"""
function merge(::Nothing, ::NamedTuple)
    return throw(
        CTBase.Exceptions.PreconditionError(
            "there is nothing to merge";
            reason="parameters are given to update, but there are no defaults to update",
        ),
    )
end

"""
$(TYPEDSIGNATURES)

Merge two `NamedTuple`s, with the second one overriding keys from the first when duplicated.

# Arguments

- `A::NamedTuple`: first set of key–value pairs.
- `B::NamedTuple`: second set of key–value pairs, takes precedence if keys overlap.

# Returns

- `::NamedTuple`: merged named tuple containing keys from both `A` and `B`.

# Example

```julia-repl
julia> merge((a=1, b=2), (b=3, c=4))
(a = 1, b = 3, c = 4)
```
"""
function merge(A::NamedTuple, B::NamedTuple)
    f(; kwargs...) = kwargs
    return NamedTuple(f(; A..., B...))
end

"""
$(TYPEDSIGNATURES)

Return the parameter set associated with a given problem.

# Arguments

- `problem::Symbol`: the name of the problem whose parameters are requested.

# Returns

- `::Union{Nothing,NamedTuple}`: the parameters of the problem, or `nothing` if none exist.

# Example

```julia-repl
julia> parameters_data(:beam)
(t0 = 0, tf = 1, ...)
```
"""
function parameters_data(problem::Symbol)
    return problem_metadata(problem)[:parameters]
end

"""
$(TYPEDSIGNATURES)

Return the parameter set associated with a given problem, optionally merged with user-supplied parameters.

# Arguments

- `problem::Symbol`: the name of the problem.
- `parameters::Union{Nothing,NamedTuple}`: user-supplied parameters to override or extend the defaults.  
  If `nothing`, returns the default parameters unchanged.

# Returns

- `::Union{Nothing,NamedTuple}`: the merged parameters.  
  Throws `CTBase.Exceptions.PreconditionError` if parameters are given to a problem that has none.

# Example

```julia-repl
julia> parameters_data(:beam, (tf = 2,))
(t0 = 0, tf = 2, ...)
```
"""
function parameters_data(problem::Symbol, parameters::Union{Nothing,NamedTuple})
    try
        return merge(parameters_data(problem), parameters)
    catch e
        if e isa CTBase.Exceptions.PreconditionError
            throw(
                CTBase.Exceptions.PreconditionError(
                    "there are no parameters to merge";
                    reason="problem $(problem) has no parameters",
                    suggestion="call $(problem) without the parameters keyword",
                ),
            )
        else
            rethrow(e)
        end
    end
end

"""
$(TYPEDSIGNATURES)

Return the initial guess of `problem` for its default parameters, merged with `parameters`
if given: `(state=…, control=…, variable=…)`, each component a constant, a vector, or a
function of the time `t`.

The initial guess is shared by every modeling (#377): it is a function of the parameters in
the metadata of the problem (`ext/MetaData/<problem>.jl`). The OptimalControl modelings pass
it as is; JuMP evaluates it at the nodes of the scheme. Every modeling takes another one with
the keyword `init` when the problem is built.

# Example

```julia-repl
julia> OptimalControlProblems.initial_guess_data(:beam)
(state = [0.05, 0.1], control = 0.1)
```
"""
function initial_guess_data(problem::Symbol, parameters::Union{Nothing,NamedTuple}=nothing)
    return problem_metadata(problem)[:init](parameters_data(problem, parameters))
end

# The initial guess a problem is built with: `init` if given, otherwise the one of the
# metadata for the parameters `params` of the problem.
function _initial_guess(problem::Symbol, params, init)
    isnothing(init) || return init
    return problem_metadata(problem)[:init](params)
end

